import { useState } from 'react';
import type { BriefingFixture, BriefingSource, EvidenceView } from '../types';
import { FINDING_LABEL, evidenceForDecision, findingFor } from '../evidence';
import type { ProposalDraft } from './ConfirmModal';
import TypeBadge from './TypeBadge';

interface Props {
  fixture: BriefingFixture;
  source: BriefingSource;
  error: string | null;
  onRefresh: () => void;
  onEvidence: (v: EvidenceView) => void;
  onAsk: (text: string) => void;
  onPropose: (d: ProposalDraft) => void;
}

const TOP = 3;

export default function BriefingSummary({ fixture, source, error, onRefresh, onEvidence, onAsk, onPropose }: Props) {
  const { briefing } = fixture;
  const [showAll, setShowAll] = useState(false);
  const decisions = showAll ? briefing.decisions : briefing.decisions.slice(0, TOP);
  const y = briefing.yesterday;

  return (
    <section className="briefing" aria-labelledby="briefing-title">
      <div className="briefing-head">
        <div>
          <h2 id="briefing-title">Morning briefing · {briefing.as_of_date}</h2>
          <p className="headline">
            <strong>{briefing.at_risk.count} orders at risk</strong> · {briefing.total_findings} findings ·{' '}
            {briefing.decisions.length} items need your decision
            {y.is_workday ? '' : ' · yesterday was a rest day'}
          </p>
        </div>
        <p className="muted small provenance" role="status">
          {source === 'live' && (
            <>
              Live from <code>{fixture.generator}</code> at {new Date(fixture.generated_at).toLocaleString()}, backend{' '}
              {fixture.backend_commit ?? 'unknown commit'}.
            </>
          )}
          {source === 'checking' && <>Loading the live briefing…</>}
          {source === 'snapshot' && (
            <>
              Live briefing unavailable{error ? ` (${error})` : ''}. Showing the saved snapshot generated by{' '}
              <code>{fixture.generator}</code> from backend {fixture.backend_commit ?? 'unknown commit'}.
            </>
          )}{' '}
          <button className="btn btn-small" onClick={onRefresh} disabled={source === 'checking'}>
            Refresh
          </button>
        </p>
      </div>

      <ol className="decisions">
        {decisions.map((d, i) => {
          const finding = findingFor(briefing, d);
          const orderId = (finding?.details.order_id as string | undefined) ?? undefined;
          const target = orderId ?? (finding?.details.customer as string | undefined) ?? (finding?.details.stage as string | undefined) ?? 'factory';
          return (
            <li key={d.about} className="decision">
              <div className="decision-top">
                <span className="rank" aria-label={`Priority ${i + 1}`}>#{i + 1}</span>
                <TypeBadge type={d.finding_type} />
              </div>
              <p className="about">{d.about}</p>
              <p className="suggest muted">{d.suggested_decision}</p>
              <div className="row-actions">
                <button className="btn" onClick={() => onEvidence(evidenceForDecision(briefing, d))}>
                  View evidence
                </button>
                <button
                  className="btn"
                  onClick={() =>
                    onAsk(orderId ? `What is the latest status of ${orderId}?` : `Tell me more about: ${d.about}`)
                  }
                >
                  Ask Co-Pilot
                </button>
                <button
                  className="btn btn-primary"
                  onClick={() =>
                    onPropose({
                      kind: 'reminder',
                      target,
                      text: `Follow up: ${d.about} ${d.suggested_decision}`,
                      reason: `${FINDING_LABEL[d.finding_type]} in the ${briefing.as_of_date} briefing`,
                    })
                  }
                >
                  Create reminder…
                </button>
              </div>
            </li>
          );
        })}
      </ol>
      {briefing.decisions.length > TOP && (
        <button className="link" onClick={() => setShowAll((s) => !s)} aria-expanded={showAll}>
          {showAll ? 'Show top 3 only' : `Show all ${briefing.decisions.length} items`}
        </button>
      )}
      {briefing.warnings.length > 0 && (
        <ul className="warnings small">
          {briefing.warnings.map((w) => (
            <li key={w}>ⓘ {w}</li>
          ))}
        </ul>
      )}
    </section>
  );
}
